//! Bench-only guard for the CLOD crossfade CSV emitted by
//! `voxel::pages::crossfade_stats_export`.
//!
//! This validates the runtime/material bridge introduced for PoC-style CLOD
//! cut crossfades. It intentionally reads the CSV contract only, so it can run
//! after benches without depending on Bevy startup or renderer state.

use std::collections::HashSet;
use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use clap::Parser;
use serde::Deserialize;

#[derive(Parser, Debug)]
#[command(
    about = "Validate CLOD crossfade runtime stats exported by VOXEL_CLOD_CROSSFADE_STATS_CSV=1",
    version
)]
struct Args {
    /// CSV generated by VOXEL_CLOD_CROSSFADE_STATS_CSV=1.
    #[arg(default_value = "perf-dumps/clod-crossfade-runtime.csv")]
    csv: PathBuf,

    /// Guard configuration TOML.
    #[arg(long, default_value = "assets/config/clod_crossfade_guard.toml")]
    config: PathBuf,

    /// Treat warnings as process failures.
    #[arg(long)]
    fail_on_warning: bool,
}

#[derive(Debug, Deserialize, Default)]
struct GuardConfig {
    #[serde(default)]
    crossfade: CrossfadeGuardConfig,
}

#[derive(Debug, Deserialize, Clone, Copy)]
#[serde(default)]
struct CrossfadeGuardConfig {
    min_samples: usize,
    require_material_enabled: bool,
    max_material_disabled_frames: usize,
    min_transitions_observed: usize,
    require_alpha_motion_when_transitioning: bool,
    min_allowed_alpha: f32,
    max_allowed_alpha: f32,
    max_final_fade_out_pages: usize,
    max_final_fade_out_entities: usize,
    max_rows_with_fading_runtime_and_no_entities: usize,
    max_role_sum_mismatch_rows: usize,
    max_visible_faded_entity_overflow_rows: usize,
}

impl Default for CrossfadeGuardConfig {
    fn default() -> Self {
        Self {
            min_samples: 1,
            require_material_enabled: true,
            max_material_disabled_frames: 0,
            min_transitions_observed: 0,
            require_alpha_motion_when_transitioning: true,
            min_allowed_alpha: 0.0,
            max_allowed_alpha: 1.0,
            max_final_fade_out_pages: 0,
            max_final_fade_out_entities: 0,
            max_rows_with_fading_runtime_and_no_entities: 0,
            max_role_sum_mismatch_rows: 0,
            max_visible_faded_entity_overflow_rows: 0,
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
struct CrossfadeRow {
    frame: u64,
    transition_id: u64,
    material_enabled: bool,
    stable_pages: usize,
    fade_in_pages: usize,
    fade_out_pages: usize,
    page_entities: usize,
    faded_entities: usize,
    visible_faded_entities: usize,
    stable_entities: usize,
    fade_in_entities: usize,
    fade_out_entities: usize,
    min_alpha: f32,
    max_alpha: f32,
}

#[derive(Debug, Default, PartialEq)]
struct CrossfadeSummary {
    samples: usize,
    first_frame: u64,
    last_frame: u64,
    transitions_observed: usize,
    material_disabled_frames: usize,
    fading_runtime_rows: usize,
    rows_with_fading_runtime_and_no_entities: usize,
    role_sum_mismatch_rows: usize,
    visible_faded_entity_overflow_rows: usize,
    invalid_alpha_rows: usize,
    min_alpha_seen: f32,
    max_alpha_seen: f32,
    max_fade_in_pages: usize,
    max_fade_out_pages: usize,
    max_fade_in_entities: usize,
    max_fade_out_entities: usize,
    final_fade_out_pages: usize,
    final_fade_out_entities: usize,
}

#[derive(Debug, Default, PartialEq)]
struct GuardReport {
    warnings: Vec<String>,
    failures: Vec<String>,
    summary: CrossfadeSummary,
}

fn main() -> ExitCode {
    let args = Args::parse();
    let config = match read_config(&args.config) {
        Ok(config) => config,
        Err(err) => {
            eprintln!("failed to read {:?}: {err}", args.config);
            return ExitCode::from(2);
        }
    };
    let csv = match fs::read_to_string(&args.csv) {
        Ok(csv) => csv,
        Err(err) => {
            eprintln!("failed to read {:?}: {err}", args.csv);
            return ExitCode::from(2);
        }
    };
    let rows = match parse_csv(&csv) {
        Ok(rows) => rows,
        Err(err) => {
            eprintln!("failed to parse {:?}: {err}", args.csv);
            return ExitCode::from(2);
        }
    };

    let report = evaluate(&rows, config.crossfade);
    print_report(&args.csv, &report);

    if !report.failures.is_empty() || (args.fail_on_warning && !report.warnings.is_empty()) {
        ExitCode::from(1)
    } else {
        ExitCode::SUCCESS
    }
}

fn read_config(path: &PathBuf) -> Result<GuardConfig, String> {
    let text = fs::read_to_string(path).map_err(|err| err.to_string())?;
    toml::from_str(&text).map_err(|err| err.to_string())
}

fn parse_csv(text: &str) -> Result<Vec<CrossfadeRow>, String> {
    let mut lines = text.lines().filter(|line| !line.trim().is_empty());
    let Some(header_line) = lines.next() else {
        return Err("empty CSV".to_string());
    };

    let headers: Vec<&str> = header_line.split(',').map(str::trim).collect();
    let required = [
        "frame",
        "transition_id",
        "material_enabled",
        "stable_pages",
        "fade_in_pages",
        "fade_out_pages",
        "page_entities",
        "faded_entities",
        "visible_faded_entities",
        "stable_entities",
        "fade_in_entities",
        "fade_out_entities",
        "min_alpha",
        "max_alpha",
    ];
    for name in required {
        if !headers.contains(&name) {
            return Err(format!("missing required column `{name}`"));
        }
    }

    let mut rows = Vec::new();
    for (line_number, line) in lines.enumerate() {
        let fields: Vec<&str> = line.split(',').map(str::trim).collect();
        if fields.len() != headers.len() {
            return Err(format!(
                "line {} has {} fields, expected {}",
                line_number + 2,
                fields.len(),
                headers.len()
            ));
        }
        rows.push(parse_row(&headers, &fields, line_number + 2)?);
    }

    Ok(rows)
}

fn parse_row(headers: &[&str], fields: &[&str], line: usize) -> Result<CrossfadeRow, String> {
    Ok(CrossfadeRow {
        frame: parse(headers, fields, "frame", line)?,
        transition_id: parse(headers, fields, "transition_id", line)?,
        material_enabled: parse_bool(value(headers, fields, "material_enabled", line)?, line)?,
        stable_pages: parse(headers, fields, "stable_pages", line)?,
        fade_in_pages: parse(headers, fields, "fade_in_pages", line)?,
        fade_out_pages: parse(headers, fields, "fade_out_pages", line)?,
        page_entities: parse(headers, fields, "page_entities", line)?,
        faded_entities: parse(headers, fields, "faded_entities", line)?,
        visible_faded_entities: parse(headers, fields, "visible_faded_entities", line)?,
        stable_entities: parse(headers, fields, "stable_entities", line)?,
        fade_in_entities: parse(headers, fields, "fade_in_entities", line)?,
        fade_out_entities: parse(headers, fields, "fade_out_entities", line)?,
        min_alpha: parse(headers, fields, "min_alpha", line)?,
        max_alpha: parse(headers, fields, "max_alpha", line)?,
    })
}

fn value<'a>(
    headers: &[&str],
    fields: &'a [&str],
    name: &str,
    line: usize,
) -> Result<&'a str, String> {
    let Some(index) = headers.iter().position(|header| *header == name) else {
        return Err(format!("missing column `{name}`"));
    };
    fields
        .get(index)
        .copied()
        .ok_or_else(|| format!("line {line}: missing field `{name}`"))
}

fn parse<T>(headers: &[&str], fields: &[&str], name: &str, line: usize) -> Result<T, String>
where
    T: std::str::FromStr,
    T::Err: std::fmt::Display,
{
    value(headers, fields, name, line)?
        .parse::<T>()
        .map_err(|err| format!("line {line}: invalid `{name}`: {err}"))
}

fn parse_bool(raw: &str, line: usize) -> Result<bool, String> {
    match raw {
        "true" | "1" | "yes" | "on" => Ok(true),
        "false" | "0" | "no" | "off" => Ok(false),
        _ => Err(format!("line {line}: invalid bool `{raw}`")),
    }
}

fn evaluate(rows: &[CrossfadeRow], config: CrossfadeGuardConfig) -> GuardReport {
    let mut report = GuardReport {
        summary: summarize(rows),
        ..Default::default()
    };
    let summary = &report.summary;

    if summary.samples < config.min_samples {
        report.failures.push(format!(
            "too few samples: got {}, expected at least {}",
            summary.samples, config.min_samples
        ));
    }

    if config.require_material_enabled
        && summary.material_disabled_frames > config.max_material_disabled_frames
    {
        report.failures.push(format!(
            "material disabled for {} frames, allowed {}",
            summary.material_disabled_frames, config.max_material_disabled_frames
        ));
    }

    if summary.transitions_observed < config.min_transitions_observed {
        report.failures.push(format!(
            "too few transitions observed: got {}, expected at least {}",
            summary.transitions_observed, config.min_transitions_observed
        ));
    }

    if summary.invalid_alpha_rows > 0 {
        report.failures.push(format!(
            "{} rows have alpha outside [{}, {}]",
            summary.invalid_alpha_rows, config.min_allowed_alpha, config.max_allowed_alpha
        ));
    }

    if config.require_alpha_motion_when_transitioning && summary.fading_runtime_rows > 0 {
        let alpha_span = summary.max_alpha_seen - summary.min_alpha_seen;
        if alpha_span <= f32::EPSILON {
            report.failures.push(format!(
                "transition alpha never moved: min={} max={}",
                summary.min_alpha_seen, summary.max_alpha_seen
            ));
        } else if summary.min_alpha_seen >= 1.0 || summary.max_alpha_seen <= 0.0 {
            report.warnings.push(format!(
                "transition alpha did not cross a useful fade range: min={} max={}",
                summary.min_alpha_seen, summary.max_alpha_seen
            ));
        }
    }

    if summary.final_fade_out_pages > config.max_final_fade_out_pages {
        report.failures.push(format!(
            "final fade-out pages leak: got {}, allowed {}",
            summary.final_fade_out_pages, config.max_final_fade_out_pages
        ));
    }

    if summary.final_fade_out_entities > config.max_final_fade_out_entities {
        report.failures.push(format!(
            "final fade-out entity leak: got {}, allowed {}",
            summary.final_fade_out_entities, config.max_final_fade_out_entities
        ));
    }

    if summary.rows_with_fading_runtime_and_no_entities
        > config.max_rows_with_fading_runtime_and_no_entities
    {
        report.failures.push(format!(
            "runtime reported fading pages without ECS fade entities in {} rows, allowed {}",
            summary.rows_with_fading_runtime_and_no_entities,
            config.max_rows_with_fading_runtime_and_no_entities
        ));
    }

    if summary.role_sum_mismatch_rows > config.max_role_sum_mismatch_rows {
        report.failures.push(format!(
            "fade role counters did not sum to faded_entities in {} rows, allowed {}",
            summary.role_sum_mismatch_rows, config.max_role_sum_mismatch_rows
        ));
    }

    if summary.visible_faded_entity_overflow_rows > config.max_visible_faded_entity_overflow_rows {
        report.failures.push(format!(
            "visible faded entities exceeded faded_entities in {} rows, allowed {}",
            summary.visible_faded_entity_overflow_rows,
            config.max_visible_faded_entity_overflow_rows
        ));
    }

    report
}

fn summarize(rows: &[CrossfadeRow]) -> CrossfadeSummary {
    if rows.is_empty() {
        return CrossfadeSummary::default();
    }

    let mut transitions = HashSet::new();
    let mut summary = CrossfadeSummary {
        samples: rows.len(),
        first_frame: rows.first().map(|row| row.frame).unwrap_or_default(),
        last_frame: rows.last().map(|row| row.frame).unwrap_or_default(),
        min_alpha_seen: f32::INFINITY,
        max_alpha_seen: f32::NEG_INFINITY,
        ..Default::default()
    };

    for row in rows {
        transitions.insert(row.transition_id);
        if !row.material_enabled {
            summary.material_disabled_frames += 1;
        }
        if row.fade_in_pages > 0 || row.fade_out_pages > 0 {
            summary.fading_runtime_rows += 1;
            if row.faded_entities == 0 {
                summary.rows_with_fading_runtime_and_no_entities += 1;
            }
        }
        if row.stable_entities + row.fade_in_entities + row.fade_out_entities != row.faded_entities
        {
            summary.role_sum_mismatch_rows += 1;
        }
        if row.visible_faded_entities > row.faded_entities {
            summary.visible_faded_entity_overflow_rows += 1;
        }
        if row.min_alpha < 0.0 || row.max_alpha > 1.0 || row.min_alpha > row.max_alpha {
            summary.invalid_alpha_rows += 1;
        }
        summary.min_alpha_seen = summary.min_alpha_seen.min(row.min_alpha);
        summary.max_alpha_seen = summary.max_alpha_seen.max(row.max_alpha);
        summary.max_fade_in_pages = summary.max_fade_in_pages.max(row.fade_in_pages);
        summary.max_fade_out_pages = summary.max_fade_out_pages.max(row.fade_out_pages);
        summary.max_fade_in_entities = summary.max_fade_in_entities.max(row.fade_in_entities);
        summary.max_fade_out_entities = summary.max_fade_out_entities.max(row.fade_out_entities);
    }

    // transition_id 0 is the initial stable cut. Count only actual cut changes.
    summary.transitions_observed = transitions.iter().filter(|id| **id != 0).count();
    summary.final_fade_out_pages = rows
        .last()
        .map(|row| row.fade_out_pages)
        .unwrap_or_default();
    summary.final_fade_out_entities = rows
        .last()
        .map(|row| row.fade_out_entities)
        .unwrap_or_default();

    summary
}

fn print_report(path: &PathBuf, report: &GuardReport) {
    let summary = &report.summary;
    println!("CLOD crossfade guard: {:?}", path);
    println!("  samples: {}", summary.samples);
    println!("  frames: {}..{}", summary.first_frame, summary.last_frame);
    println!("  transitions observed: {}", summary.transitions_observed);
    println!(
        "  material disabled frames: {}",
        summary.material_disabled_frames
    );
    println!("  fading runtime rows: {}", summary.fading_runtime_rows);
    println!(
        "  alpha seen: {}..{}",
        summary.min_alpha_seen, summary.max_alpha_seen
    );
    println!(
        "  max fade-in pages/entities: {}/{}",
        summary.max_fade_in_pages, summary.max_fade_in_entities
    );
    println!(
        "  max fade-out pages/entities: {}/{}",
        summary.max_fade_out_pages, summary.max_fade_out_entities
    );
    println!(
        "  final fade-out pages/entities: {}/{}",
        summary.final_fade_out_pages, summary.final_fade_out_entities
    );

    for warning in &report.warnings {
        println!("warning: {warning}");
    }
    for failure in &report.failures {
        println!("failure: {failure}");
    }
    if report.failures.is_empty() {
        println!("result: PASS");
    } else {
        println!("result: FAIL");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_csv() -> &'static str {
        "frame,transition_id,material_enabled,stable_pages,fade_in_pages,fade_out_pages,page_entities,faded_entities,visible_faded_entities,stable_entities,fade_in_entities,fade_out_entities,min_alpha,max_alpha\n\
10,0,true,4,0,0,4,4,4,4,0,0,1.0,1.0\n\
11,1,true,2,2,2,6,6,6,2,2,2,0.25,0.75\n\
22,1,true,4,0,0,4,4,4,4,0,0,1.0,1.0\n"
    }

    #[test]
    fn parses_crossfade_csv() {
        let rows = parse_csv(sample_csv()).unwrap();
        assert_eq!(rows.len(), 3);
        assert_eq!(rows[1].transition_id, 1);
        assert_eq!(rows[1].fade_out_pages, 2);
        assert_eq!(rows[1].min_alpha, 0.25);
    }

    #[test]
    fn passes_clean_crossfade() {
        let rows = parse_csv(sample_csv()).unwrap();
        let report = evaluate(&rows, CrossfadeGuardConfig::default());
        assert!(report.failures.is_empty(), "{report:?}");
        assert_eq!(report.summary.transitions_observed, 1);
        assert_eq!(report.summary.final_fade_out_pages, 0);
    }

    #[test]
    fn fails_final_fade_out_leak() {
        let csv = "frame,transition_id,material_enabled,stable_pages,fade_in_pages,fade_out_pages,page_entities,faded_entities,visible_faded_entities,stable_entities,fade_in_entities,fade_out_entities,min_alpha,max_alpha\n\
1,1,true,2,1,1,4,4,4,2,1,1,0.5,0.5\n";
        let rows = parse_csv(csv).unwrap();
        let report = evaluate(&rows, CrossfadeGuardConfig::default());
        assert!(
            report
                .failures
                .iter()
                .any(|failure| failure.contains("final fade-out pages leak"))
        );
    }

    #[test]
    fn fails_material_disabled() {
        let csv = "frame,transition_id,material_enabled,stable_pages,fade_in_pages,fade_out_pages,page_entities,faded_entities,visible_faded_entities,stable_entities,fade_in_entities,fade_out_entities,min_alpha,max_alpha\n\
1,0,false,4,0,0,4,4,4,4,0,0,1.0,1.0\n";
        let rows = parse_csv(csv).unwrap();
        let report = evaluate(&rows, CrossfadeGuardConfig::default());
        assert!(
            report
                .failures
                .iter()
                .any(|failure| failure.contains("material disabled"))
        );
    }
}
